package alloy

import (
	"fmt"
	"strings"

	pc "github.com/sourcenetwork/acp_core/internal/policy_compiler"
)

// EmitAssumptions renders application assumptions as <module>_assumptions.als.
//
// Each assumption is a pred, and pred `assumptions` combines all of them.
// No facts are emitted: models opt into the assumptions where they need them,
// eg. `run { assumptions and ... }` or `check { assumptions => ... }`.
func EmitAssumptions(model *pc.Model, module string, assumptions []pc.Assumption) File {
	e := newEmitter(model, module)
	b := &strings.Builder{}
	fmt.Fprintf(b, "module %v_assumptions\n\n", e.module)
	fmt.Fprintf(b, "// Generated by the acp_core policy compiler from policy %q. Do not edit.\n", e.model.Name)
	b.WriteString("//\n// Application assumptions: invariants the application enforces over relationships, which acp_core does not.\n")
	b.WriteString("// Use them to generate instances the application can actually produce: run { assumptions and ... }\n\n")
	fmt.Fprintf(b, "open %v\n", e.module)

	var names []string
	for _, a := range assumptions {
		name, comment, body := e.assumption(a)
		names = append(names, name)
		fmt.Fprintf(b, "\n// %v\npred %v {\n    %v\n}\n", comment, name, strings.Join(body, "\n    "))
	}

	b.WriteString("\npred assumptions {\n")
	for _, name := range names {
		fmt.Fprintf(b, "    %v\n", name)
	}
	b.WriteString("}\n")
	return File{Name: e.module + "_assumptions.als", Content: b.String()}
}

// assumption returns the pred name, a description and the pred body lines of an assumption
func (e *emitter) assumption(a pc.Assumption) (name, comment string, body []string) {
	switch a := a.(type) {
	case *pc.Disjoint:
		name = "disjoint_" + a.Resource + "_" + strings.Join(a.Relations, "_")
		comment = fmt.Sprintf("a subject is never related to a %v through more than one of: %v", a.Resource, strings.Join(a.Relations, ", "))
		for _, pair := range a.Pairs {
			body = append(body, fmt.Sprintf("no %v & %v", e.qualified(pair[0]), e.qualified(pair[1])))
		}
	case *pc.AtMostOne:
		name = "at_most_one_" + a.Resource + "_" + a.Relation
		comment = fmt.Sprintf("a %v has at most one %v", a.Resource, a.Relation)
		var conds []string
		for i, f := range a.Fields {
			conds = append(conds, "lone o."+e.field(f))
			for _, other := range a.Fields[i+1:] {
				conds = append(conds, fmt.Sprintf("(no o.%v or no o.%v)", e.field(f), e.field(other)))
			}
		}
		body = []string{fmt.Sprintf("all o: %v | %v", sigName(a.Resource), strings.Join(conds, " and "))}
	case *pc.Acyclic:
		name = "acyclic_" + a.Resource + "_" + a.Relation
		comment = fmt.Sprintf("following %v from a %v never leads back to it", a.Relation, a.Resource)
		body = []string{fmt.Sprintf("no o: %v | o in o.^%v", sigName(a.Resource), e.fields(a.Fields))}
	}
	return name, comment, body
}

// qualified renders a field as a relation of its signature, which is required when
// combining fields outside of a join (eg. `(Doc <: owner) & (Doc <: editor)`)
func (e *emitter) qualified(f *pc.Field) string {
	return "(" + sigName(f.Resource) + " <: " + f.Name + ")"
}
