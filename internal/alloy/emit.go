// package alloy emits policy compiler models as Alloy modules
package alloy

import (
	"fmt"
	"strings"

	pc "github.com/sourcenetwork/acp_core/internal/policy_compiler"
)

// File is an emitted Alloy module
type File struct {
	Name    string
	Content string
}

// Emit renders a Model into a bundle of Alloy modules:
// <module>.als declares the signatures, relations and permissions, and
// <module>_management.als declares the authorities and influencers.
//
// module defaults to the policy name if empty.
func Emit(model *pc.Model, module string) []File {
	e := newEmitter(model, module)
	return []File{
		{Name: e.module + ".als", Content: e.core()},
		{Name: e.module + "_management.als", Content: e.management()},
	}
}

type emitter struct {
	model  *pc.Model
	module string
	// ambiguous contains field names declared by more than one resource,
	// which must be qualified with their signature
	ambiguous map[string]bool
}

func newEmitter(model *pc.Model, module string) *emitter {
	if module == "" {
		module = model.Name
	}
	declared := make(map[string]int)
	for _, r := range model.Resources {
		seen := make(map[string]bool)
		for _, f := range r.Fields {
			if !seen[f.Name] {
				seen[f.Name] = true
				declared[f.Name]++
			}
		}
	}
	ambiguous := make(map[string]bool)
	for name, count := range declared {
		ambiguous[name] = count > 1
	}
	return &emitter{
		model:     model,
		module:    moduleName(module),
		ambiguous: ambiguous,
	}
}

func (e *emitter) core() string {
	b := &strings.Builder{}
	fmt.Fprintf(b, "module %v\n\n", e.module)
	fmt.Fprintf(b, "// Generated by the acp_core policy compiler from policy %q. Do not edit.\n\n", e.model.Name)
	// every resource is a top-level sig, so a scope (`for 4`) bounds each resource separately
	b.WriteString("sig Actor {}\n")

	for _, r := range e.model.Resources {
		fmt.Fprintf(b, "\nsig %v {\n", sigName(r.Name))
		for _, f := range r.Fields {
			mult := "set"
			if f.One {
				mult = "one"
			}
			fmt.Fprintf(b, "    %v: %v %v,\n", f.Name, mult, sigName(f.Target))
		}
		b.WriteString("}\n")
	}

	for _, r := range e.model.Resources {
		e.section(b, fmt.Sprintf("%v relations", r.Name), r.Relations)
		e.section(b, fmt.Sprintf("%v permissions", r.Name), r.Permissions)
	}
	return b.String()
}

func (e *emitter) management() string {
	b := &strings.Builder{}
	fmt.Fprintf(b, "module %v_management\n\n", e.module)
	fmt.Fprintf(b, "// Generated by the acp_core policy compiler from policy %q. Do not edit.\n\n", e.model.Name)
	fmt.Fprintf(b, "open %v\n", e.module)

	for _, r := range e.model.Resources {
		e.section(b, fmt.Sprintf("%v authorities: actors which may manage each relation", r.Name), r.Authorities)
	}
	for _, r := range e.model.Resources {
		e.section(b, fmt.Sprintf("%v influencers: actors which may change the value of each permission", r.Name), r.Influencers)
	}
	return b.String()
}

func (e *emitter) section(b *strings.Builder, title string, computations []*pc.Computation) {
	if len(computations) == 0 {
		return
	}
	fmt.Fprintf(b, "\n// %v\n", title)
	for _, c := range computations {
		b.WriteString("\n")
		if c.Source != "" {
			fmt.Fprintf(b, "// %v: %v\n", c.Name, c.Source)
		}
		fmt.Fprintf(b, "fun %v: %v->Actor {\n    %v\n}\n", computationName(c), sigName(c.Resource), e.expr(c.Expr))
	}
}

var operators = map[pc.Op]string{
	pc.Union:        "+",
	pc.Difference:   "-",
	pc.Intersection: "&",
}

func (e *emitter) expr(x pc.Expr) string {
	switch x := x.(type) {
	case *pc.Tuples:
		return e.field(x.Field)
	case *pc.Ref:
		return computationName(x.To)
	case *pc.Join:
		if ref, ok := x.Expr.(*pc.Ref); ok {
			return e.field(x.Field) + "." + computationName(ref.To)
		}
		return e.field(x.Field) + ".(" + e.expr(x.Expr) + ")"
	case *pc.Closure:
		return "(*" + e.fields(x.Fields) + ").(" + e.expr(x.Local) + ")"
	case *pc.Binary:
		return e.operand(x.Op, x.Left) + " " + operators[x.Op] + " " + e.operand(x.Op, x.Right)
	default:
		return "none->none"
	}
}

// operand renders a Binary operand, parenthesizing nested binaries
// unless they are unions within a union
func (e *emitter) operand(parent pc.Op, x pc.Expr) string {
	s := e.expr(x)
	if b, ok := x.(*pc.Binary); ok && !(parent == pc.Union && b.Op == pc.Union) {
		return "(" + s + ")"
	}
	return s
}

func (e *emitter) field(f *pc.Field) string {
	if e.ambiguous[f.Name] {
		return "(" + sigName(f.Resource) + " <: " + f.Name + ")"
	}
	return f.Name
}

func (e *emitter) fields(fields []*pc.Field) string {
	if len(fields) == 1 {
		return e.field(fields[0])
	}
	var names []string
	for _, f := range fields {
		names = append(names, e.field(f))
	}
	return "(" + strings.Join(names, " + ") + ")"
}

func computationName(c *pc.Computation) string {
	switch c.Kind {
	case pc.KindAuthority:
		return "authority_" + c.Resource + "_" + c.Name
	case pc.KindInfluence:
		return c.Resource + "_" + c.Name + "_influencers"
	default:
		return c.Resource + "_" + c.Name
	}
}

// sigName capitalizes a resource name, mapping the actor target to Actor
func sigName(resource string) string {
	if resource == pc.ActorTarget {
		return "Actor"
	}
	return strings.ToUpper(resource[:1]) + resource[1:]
}

// moduleName turns a policy name into a valid Alloy module name
func moduleName(name string) string {
	name = strings.Map(func(r rune) rune {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') || r == '_' {
			return r
		}
		return '_'
	}, strings.ToLower(name))
	if name == "" {
		return "policy"
	}
	if name[0] >= '0' && name[0] <= '9' {
		name = "policy_" + name
	}
	return name
}
